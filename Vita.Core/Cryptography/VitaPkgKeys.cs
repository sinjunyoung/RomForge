namespace Vita.Core.Cryptography;

public static class VitaPkgKeys
{
    public static readonly byte[] PkgVita2 = [0xe3, 0x1a, 0x70, 0xc9, 0xce, 0x1d, 0xd7, 0x2b, 0xf3, 0xc0, 0x62, 0x29, 0x63, 0xf2, 0xec, 0xcb];

    public static readonly byte[] PkgVita3 = [0x42, 0x3a, 0xca, 0x3a, 0x2b, 0xd5, 0x64, 0x9f, 0x96, 0x86, 0xab, 0xad, 0x6f, 0xd8, 0x80, 0x1f];

    public static readonly byte[] PkgVita4 = [0xaf, 0x07, 0xfd, 0x59, 0x65, 0x25, 0x27, 0xba, 0xf1, 0x33, 0x89, 0x66, 0x8b, 0x17, 0xd9, 0xea];

    public static byte[] DeriveMainKey(int keyType, ReadOnlySpan<byte> iv)
    {
        byte[] masterKey = keyType switch
        {
            2 => PkgVita2,
            3 => PkgVita3,
            4 => PkgVita4,
            _ => throw new NotSupportedException($"지원하지 않는 PKG key_type: {keyType}")
        };

        return VitaAes128Ctr.EcbEncryptSingleBlock(masterKey, iv);
    }
}